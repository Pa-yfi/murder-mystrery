# سازگاری: COMPOSITIONS همان سناریوی کلاسیک است
COMPOSITIONS: Dict[int, List[str]] = SCENARIOS[DEFAULT_SCENARIO][2]


def scenario_name(key: str) -> str:
    return SCENARIOS.get(key, SCENARIOS[DEFAULT_SCENARIO])[0]


def composition(n: int, scenario: str = DEFAULT_SCENARIO) -> List[str]:
    comps = SCENARIOS.get(scenario, SCENARIOS[DEFAULT_SCENARIO])[2]
    if n not in comps:
        raise ValueError(f"تعداد بازیکن باید بین {_fa(min(comps))} تا {_fa(max(comps))} باشد.")
    return list(comps[n])


def balance_report(n: int, scenario: str = DEFAULT_SCENARIO) -> Dict[str, int]:
    c = composition(n, scenario)
    out = {a.value: 0 for a in Align}
    for r in c:
        out[ROLES[r].align.value] += 1
    return out


def validate_composition(n: int, scenario: str = DEFAULT_SCENARIO) -> bool:
    """قواعد تعادل (بر پایه‌ی پژوهش مافیا/ور‌ولف — ویکی‌پدیا: نسبت مافیا حدود ⅓ تا √n):
    - همیشه دقیقاً یک بازجو و یک کارآگاه
    - قاتل‌ها اقلیت‌اند: کمتر از شهر و کمتر از نصف کل
    - نقش‌های تهدیدآمیز (قاتل‌ها + جانی سریالی) ۱۵٪ تا ۴۵٪ (۶ نفره: ۱ قاتل + سپر بلا)
    - همه‌ی نقش‌های غیرشهری روی هم حداکثر ۵۰٪
    - همیشه دست‌کم یک نقشِ قاتل‌دار (قاتل)
    """
    c = composition(n, scenario)
    k = sum(1 for r in c if ROLES[r].align is Align.KILLER)
    city = sum(1 for r in c if ROLES[r].align is Align.CITY)
    hostile = k + sum(1 for r in c if r in HOSTILE_NEUTRAL)
    hidden = sum(1 for r in c if ROLES[r].align is not Align.CITY)
    return (len(c) == n and c.count("بازجو") == 1 and c.count("کارآگاه") == 1
            and "قاتل" in c and 0 < k < city and k * 2 < n
            and 0.15 <= hostile / n <= 0.45 and hidden / n <= 0.50)


def scenario_card(key: str, n: int) -> str:
    """متنِ کوتاهِ سناریو برای لابی: چه نقش‌هایی در بازی هست."""
    name, desc, comps = SCENARIOS.get(key, SCENARIOS[DEFAULT_SCENARIO])
    roles = comps.get(n)
    lst = "، ".join(f"{ROLES[r].emoji} {r}" for r in roles) if roles else \
        f"(برای {_fa(min(comps))} تا {_fa(max(comps))} نفر)"
    return f"🎭 سناریو: *{name}* — {desc}\n🃏 نقش‌های این میز: {lst}"


# ایده ۵: کول‌داون نقش — از تکرار نقش یکسان برای یک بازیکن در بازی بعدی جلوگیری می‌کند
def assign_with_cooldown(uids, n, rng, last_roles, scenario: str = DEFAULT_SCENARIO):
    """last_roles: dict[uid->str] نقش بازی قبلی. تلاش می‌کند نقش تکراری ندهد."""
    roles = composition(n, scenario)
    for _ in range(40):                    # چند بار به‌هم می‌زند تا کمترین تکرار
        rng.shuffle(roles)
        repeats = sum(1 for u, r in zip(uids, roles) if last_roles.get(u) == r)
        if repeats == 0:
            break
    return dict(zip(uids, roles))
