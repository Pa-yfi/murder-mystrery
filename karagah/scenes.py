def pack(scenario: str) -> str:
    return scenario if scenario in LOCATIONS else "classic"


def extra_trait(scenario: str) -> Tuple[str, Tuple[str, str, List[str]]]:
    return EXTRA_TRAITS[pack(scenario)]


def trait_text(scenario: str, trait: str, value: str) -> str:
    tpl = TRAIT_TEXT[pack(scenario)].get(trait) or TRAIT_TEXT["classic"].get(trait) or "{v}"
    return tpl.format(v=value)


def _log(s) -> Dict[str, List[str]]:
    if getattr(s, "scene_log", None) is None:
        s.scene_log = {}
    return s.scene_log


def _today(s) -> Dict[str, str]:
    """مکانِ هر صحنه‌ی امشب (یک قربانی = یک مکان)؛ هر شب از نو."""
    t = getattr(s, "scene_today", None)
    if not t or t.get("_day") != str(s.day):
        t = {"_day": str(s.day)}
        s.scene_today = t
    return t


def fresh_detail(s, loc: str, rng: random.Random) -> str:
    """جزئیاتی از loc که تا حالا در این بازی نشان داده نشده."""
    hist = _log(s).setdefault(loc, [])            # «روز|جزئیات» به ترتیبِ روزها
    used = {h.split("|", 1)[1] for h in hist}
    pool = LOCATIONS[pack(s.scenario)].get(loc) or CASE_SCENE
    left = [d for d in pool if d not in used]
    if left:
        d = rng.choice(left)
    else:
        combos = [f"ساعت {h}، {m}" for h in HOURS for m in MOTIFS]
        left = [d for d in combos if d not in used] or [f"روز {s.day}: هیچ‌چیز سرِ جایش نیست"]
        d = rng.choice(left)
    hist.append(f"{s.day}|{d}")
    return d


def history(s) -> Dict[str, List[Tuple[int, str]]]:
    """مکان → [(روز، جزئیات)] — برای «🗺️ نقشه‌ی صحنه‌ها» در پرونده."""
    out = {}
    for loc, hist in (getattr(s, "scene_log", None) or {}).items():
        out[loc] = [(int(h.split("|", 1)[0]), h.split("|", 1)[1]) for h in hist]
    return out


def location_for(s, rng: random.Random, key: Optional[str] = None) -> str:
    """مکانِ یک سرنخ. key یکسان (مثلاً یک قربانی) در همان شب = همان مکان.
    روز ۰ (سرنخ‌های اولِ پرونده) = صحنه‌ی اصلیِ پرونده."""
    if s.day == 0 and s.case:
        return f"🕯️ {s.case.place}"
    t = _today(s)
    if key is not None and key in t:
        return t[key]
    locs = list(LOCATIONS[pack(s.scenario)])
    taken = set(v for k, v in t.items() if k != "_day")
    free = [l for l in locs if l not in taken] or locs
    loc = rng.choice(free)
    if key is not None:
        t[key] = loc
    return loc


def stamp(s, rng: random.Random, key: Optional[str] = None) -> Tuple[str, str]:
    """(مکان، جزئیاتِ تازه‌ی امروزِ آن مکان) — هر مکان در هر روز فقط یک جزئیات می‌گیرد."""
    loc = location_for(s, rng, key)
    t = _today(s)
    k = "detail:" + loc
    if k not in t:
        t[k] = fresh_detail(s, loc, rng)
    return loc, t[k]


def patrol(s, rng: random.Random, limit: int = 7) -> List[Tuple[str, str]]:
    """گشتِ صبحگاهی: مکان‌هایی که قبلاً سرنخ داشته‌اند و امشب سرنخ تازه نگرفتند، هر کدام
    یک جزئیاتِ تازه نشان می‌دهند (فضاسازی — سرنخ نیست)."""
    t = _today(s)
    seen = [c.get("place") for c in s.clues if c.get("place")]
    out = []
    for loc in dict.fromkeys(reversed(seen)):
        if "detail:" + loc in t:
            continue
        d = fresh_detail(s, loc, rng)
        t["detail:" + loc] = d
        out.append((loc, d))
        if len(out) >= limit:
            break
    return out
