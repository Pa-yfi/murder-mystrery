INTERP = [
    "شاید متعلق به قاتل باشد.",
    "شاید کسی عمداً آن را آنجا گذاشته باشد (پاپوش).",
    "شاید فقط اثر یک ملاقات معمولی باشد.",
    "شاید مربوط به قبل از شب حادثه باشد.",
]


def _evidence_deck(rng: random.Random) -> List[dict]:
    kinds = rng.sample(EVID_KINDS, 6)
    deck = []
    for i, (k, e) in enumerate(kinds):
        deck.append({
            "code": f"E{i+1}",
            "title": f"{e} {k}",
            "kind": k,
            "interpretations": rng.sample(INTERP, 3),
            "misleading": i in (1, 4),   # همیشه دو مدرک گمراه‌کننده وجود دارد
        })
    return deck


def build_cases() -> List[Case]:
    out = []
    for i, (title, victim, place, weapon, motive, twist) in enumerate(RAW):
        rng = random.Random(1000 + i)   # قطعی و قابل تست
        out.append(Case(
            cid=i + 1,
            title=title,
            victim=victim,
            place=place,
            weapon=weapon,
            motive=motive,
            timeline=[
                "۲۱:۰۰ — همه در محل حاضر بودند.",
                f"۲۲:۳۰ — {victim} برای آخرین بار زنده دیده شد.",
                f"۲۳:۱۵ — صدایی از {place} شنیده شد.",
                "۰۰:۰۵ — جسد کشف شد.",
            ],
            evidence=_evidence_deck(rng),
            twist=twist,
            difficulty=1 + (i % 5),
            vehicle=build_vehicle(rng),
        ))
    return out




