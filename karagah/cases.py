EVENT_CLUE = {
    "قطعی برق": "در تاریکیِ قطعی برق کسی بدون چراغ راه می‌رفت — پس مسیر را از قبل بلد بود.",
    "طوفان": "طوفان همه‌ی ردپاها را شست؛ هر شهادتی درباره‌ی دیشب سست است.",
    "شاهد ناشناس": "شاهدی ناشناس پیغام داد: «آن‌که دیدم عجله نداشت.»",
}


def day_clue(case, day: int, facts: dict) -> str:
    """سرنخ روز n. قطعی است (seed از پرونده و روز) ولی با کارِ واقعیِ دیشب رنگ می‌گیرد."""
    if case is None:
        return ""
    rng = random.Random(case.cid * 1000 + day)
    base = rng.choice(CLUE_TEMPLATES).format(
        place=case.place, weapon=case.weapon, victim=case.victim, motive=case.motive)
    tail = []
    ev = (facts.get("event") or "").split()
    if ev and ev[0] in EVENT_CLUE:
        tail.append(EVENT_CLUE[ev[0]])
    v = facts.get("visits", 0)
    if v:
        fa = str(v).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))
        tail.append(f"دیشب {fa} رفت‌وآمد نزدیک صحنه ثبت شد.")
    else:
        tail.append("دیشب هیچ رفت‌وآمدی ثبت نشد — یا کسی بیرون نرفت، یا خوب پاک کرده.")
    if facts.get("framed"):
        tail.append("یک اثر انگشت تازه هم پیدا شد؛ اثر انگشت را می‌شود کاشت.")
    if not facts.get("killed"):
        tail.append("امشب جسدی نبود؛ این خودش یک تصمیم است، نه یک تصادف.")
    return base + " " + " ".join(tail)


# ── خودروی دیده‌شده نزدیک صحنه ──────────────────────────────────────
# رنگ و مدل *علنی* می‌شود (همه در سرنخ روز می‌بینند)، ولی شماره‌ی پلاک
# فقط در پرونده‌ی پلیس است. همین شکاف، بازجو را به یک نقشِ تحقیقاتی
# واقعی تبدیل می‌کند نه فقط کسی که دکمه‌ی حبس را می‌زند.
CAR_COLORS = ["سفید", "مشکی", "نقره‌ای", "نوک‌مدادی", "قرمز", "سرمه‌ای",
              "بژ", "سبز تیره", "آبی کاربنی", "خاکستری"]
CAR_MODELS = ["پژو ۴۰۵", "پراید ۱۳۱", "سمند LX", "تیبا", "پژو پارس",
              "دنا پلاس", "رنو L90", "کوییک", "شاهین", "پژو ۲۰۶"]
PLATE_LETTERS = ["ب", "ج", "د", "س", "ص", "ط", "ق", "ل", "م", "ن", "و", "ه"]


def _fa_digits(n, width=2) -> str:
    return str(n).zfill(width).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


def build_vehicle(rng: random.Random) -> dict:
    """یک خودرو با رنگ، مدل و پلاک ایرانی — قطعی بر اساس seed پرونده."""
    return {
        "color": rng.choice(CAR_COLORS),
        "model": rng.choice(CAR_MODELS),
        # شناسه‌ی درون‌بازی و آشکارا ساختگی است: ربات هیچ سامانه‌ی واقعیِ
        # پلاک را استعلام نمی‌کند و این رشته نباید شبیه پلاک واقعی باشد.
        "plate": (f"SIM-{rng.randint(100, 999)} "
                  f"({_fa_digits(rng.randint(11, 99))} "
                  f"{rng.choice(PLATE_LETTERS)} "
                  f"{_fa_digits(rng.randint(100, 999), 3)} — نمونه‌ی بازی)"),
    }


def vehicle_clue(case) -> str:
    """سرنخ علنی: رنگ و مدل، هرگز پلاک."""
    v = case.vehicle
    return (f"🚗 شاهدی می‌گوید یک *{v['model']} {v['color']}* نزدیک {case.place} "
            "پارک بوده. شماره‌ی پلاکش را نخوانده — ولی دوربین خوانده است.")


CASES: List[Case] = build_cases()
